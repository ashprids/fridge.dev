import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const palettes = JSON.parse(readFileSync(resolve(root, 'themes/palettes/accents.json'), 'utf8'));
const linear = value => value <= 0.04045 ? value / 12.92 : ((value + 0.055) / 1.055) ** 2.4;
const rgb = hex => hex.slice(1).match(/../g).map(value => parseInt(value, 16));
const luminance = hex => rgb(hex).map(value => linear(value / 255)).reduce((sum, value, i) => sum + value * [0.2126, 0.7152, 0.0722][i], 0);
const contrast = (a, b) => (Math.max(luminance(a), luminance(b)) + 0.05) / (Math.min(luminance(a), luminance(b)) + 0.05);

// Linear sRGB -> Oklab -> OKLCH (CSS Color 4). Hue changes retain L and C.
// https://www.w3.org/TR/css-color-4/#ok-lab
function oklch(values) {
    const [r, g, b] = values.map(value => linear(value / 255));
    const l = Math.cbrt(0.4122214708 * r + 0.5363325363 * g + 0.0514459929 * b);
    const m = Math.cbrt(0.2119034982 * r + 0.6806995451 * g + 0.1073969566 * b);
    const s = Math.cbrt(0.0883024619 * r + 0.2817188376 * g + 0.6299787005 * b);
    const lightness = 0.2104542553 * l + 0.793617785 * m - 0.0040720468 * s;
    const a = 1.9779984951 * l - 2.428592205 * m + 0.4505937099 * s;
    const bAxis = 0.0259040371 * l + 0.7827717662 * m - 0.808675766 * s;
    return [lightness, Math.hypot(a, bAxis), (Math.atan2(bAxis, a) * 180 / Math.PI + 360) % 360];
}

const nordTokens = readFileSync(resolve(root, 'themes/lib/nord/modules/tokens.css'), 'utf8');
const tintTokens = new Set([
    'theme-canvas', 'theme-ink', 'theme-border', 'theme-muted', 'theme-link', 'theme-on-accent',
    'theme-sidebar', 'theme-panel', 'theme-surface', 'theme-surface-raised', 'theme-input',
    'theme-overlay', 'theme-page-background', 'theme-accent', 'theme-accent-strong',
    'theme-focus', 'theme-disabled', 'theme-shadow-small', 'theme-shadow',
    'theme-title-1', 'theme-title-2', 'theme-title-gradient', 'hero-ascii-muted',
    'hero-ascii-1', 'hero-ascii-2', 'hero-ascii-3', 'hero-ascii-4', 'resource-ascii', 'time-ascii',
]);
const declarations = [...nordTokens.matchAll(/--([\w-]+):\s*([^;]+);/g)].filter(match => tintTokens.has(match[1]));
const header = '/* Generated by node scripts/generate-theme-accents.mjs. Do not edit directly. */\n';
let stale = false;
for (const [theme, palette] of Object.entries(palettes)) {
    let css = header;
    for (const [name, color] of Object.entries(palette.colors)) {
        if (name === palette.default) continue;
        css += `\nhtml[data-theme-accent="${name}"]:not(.access-high-contrast) body.${theme}-theme {\n`;
        if (theme === 'base16') {
            let ink = contrast(color, '#1F1F1F') >= contrast(color, '#FFFFFF') ? '#1F1F1F' : '#FFFFFF';
            if (contrast(color, ink) < 4.5) ink = '#000000';
            css += `    --base0D: ${color};\n    --base-accent-ink: ${ink};\n`;
        } else if (theme === 'gruvbox') {
            css += `    --theme-accent: ${color};\n`;
            if (contrast(color, '#282828') < 4.5) {
                css += '    --theme-on-accent: #1D2021;\n';
            }
        } else {
            const hue = oklch(rgb(color))[2].toFixed(3);
            const tint = (channels, alpha = '') => {
                const [l, c] = oklch(channels);
                return `oklch(${l.toFixed(6)} ${c.toFixed(6)} ${hue}${alpha ? ` / ${alpha}` : ''})`;
            };
            for (const [, token, value] of declarations) {
                const tinted = value
                    .replace(/#[\da-f]{6}\b/gi, hex => tint(rgb(hex)))
                    .replace(/rgb\((\d+) (\d+) (\d+)\s*\/\s*([^\)]+)\)/g, (_, r, g, b, alpha) => tint([r, g, b].map(Number), alpha));
                css += `    --${token}: ${tinted.replace(/\s*\n\s*/g, ' ')};\n`;
            }
        }
        css += '}\n';
    }
    const path = resolve(root, `themes/lib/${theme}/${theme === 'base16' ? '' : 'modules/'}accents.css`);
    if (process.argv.includes('--check')) {
        if (readFileSync(path, 'utf8') !== css) { console.error(`Stale accent CSS: ${path}`); stale = true; }
    } else {
        writeFileSync(path, css);
    }
}
if (stale) process.exitCode = 1;
